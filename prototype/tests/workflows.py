"""Runs the main workflows end to end: filters, bulk actions, decisions, validation messages, dialogs (Esc, focus), schedule, mail, pages and rights, public site.
Needs: python -m pip install playwright && python -m playwright install chromium
Run:   python tests/workflows.py   (exit code 1 = a check failed)
"""
import pathlib, re, sys
from playwright.sync_api import sync_playwright

base = (pathlib.Path(__file__).resolve().parent.parent / "index.html").as_uri()
res, errs = [], []


def check(name, cond, detail=""):
    res.append((name, bool(cond), detail))


with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width": 1280, "height": 1000}, accept_downloads=True)
